"""Output-quality judges (paper Appendix A.7): text fluency and image coherence.

Both are pointwise: Gemini sees one output and nothing else (no prompt, concept, strength or layer) and scores it
0, 1 or 2. Unsteered baselines are scored too, so quality can be reported relative to them.

    fluency(run)      reads <run>/generations/sweep_text.csv   writes <run>/scores/fluency_scores.csv
    coherence(run)    reads <run>/generations/sweep_image.csv  writes <run>/scores/coherence_scores.csv

Score tables: concept, quadrant, config, alpha, prompt_idx, score. Baselines (one per concept and prompt) have
quadrant "baseline", config "none", alpha 0. Needs GEMINI_API_KEY; runs resume from <run>/scores/*.jsonl.
"""

from __future__ import annotations

import csv
import json
import os
import sys
import threading
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

MODEL = "gemini-3.7-flash"

FLUENCY_PROMPT = """You are evaluating the linguistic fluency of a language model output.

Model output:
{text}

Rate the fluency and coherence of the output.

Use the following scale:

0 = The output is substantially incoherent, ungrammatical, or otherwise difficult to understand.
1 = The output is understandable but contains noticeable issues with grammar, coherence, or naturalness.
2 = The output is fluent, coherent, grammatical, and natural.

Focus only on linguistic quality. Do not judge whether the output follows the original instruction or expresses the target concept.

Return JSON only:
{{"score": 0 | 1 | 2, "reasoning": "<one concise sentence>"}}
"""
FLUENCY_SCHEMA = {"type": "object", "properties": {"score": {"type": "integer", "minimum": 0, "maximum": 2},
                                                   "reasoning": {"type": "string"}}, "required": ["score"]}

COHERENCE_PROMPT = """You are checking an image generated by a model for visible breakage.

Answer with one of three verdicts:

"intact": the image is coherent and well-formed. This is the expected verdict for a typical generated image; the usual look of AI-generated images (smoothness, softness, a synthetic feel) is not breakage.
"partly_broken": the content is recognizable, but there are clear artifacts, distortions, or incoherent elements, such as malformed hands or faces, merged or duplicated objects, garbled text, or corrupted regions.
"broken": severe artifacts or garbled textures dominate, or the content cannot be recognized.

Only visible breakage matters. Do not judge whether the image matches any description or expresses any concept, and do not judge style, aesthetics, or realism.

Return JSON only:
{"reasoning": "<one concise sentence naming any breakage you see, or stating that there is none>", "verdict": "intact" | "partly_broken" | "broken"}"""
COHERENCE_SCHEMA = {"type": "object",
                    "properties": {"reasoning": {"type": "string"},
                                   "verdict": {"type": "string", "enum": ["intact", "partly_broken", "broken"]}},
                    "required": ["reasoning", "verdict"], "propertyOrdering": ["reasoning", "verdict"]}
COHERENCE_SCORE = {"intact": 2, "partly_broken": 1, "broken": 0}      # verdict words, mapped to the fluency scale

COLUMNS = ["concept", "quadrant", "config", "alpha", "prompt_idx", "score"]


def items(run: str | Path, medium: str, configs=None) -> list[dict]:
    """One record per output to score: every steered row (of `configs`, if given) and one baseline per
    (concept, prompt)."""
    csv.field_size_limit(sys.maxsize)
    col = "output" if medium == "text" else "image_path"
    out, seen = [], set()
    with open(Path(run) / "generations" / f"sweep_{medium}.csv", newline="") as f:
        for r in csv.DictReader(f):
            alpha = float(r["alpha"])
            if alpha == 0:
                key = (r["concept"], r["prompt_idx"])
                if key in seen:
                    continue
                seen.add(key)
                rec = {"concept": r["concept"], "quadrant": "baseline", "config": "none", "alpha": "0"}
            else:
                if configs and r["config"] not in configs:
                    continue
                rec = {"concept": r["concept"], "quadrant": r["quadrant"], "config": r["config"], "alpha": f"{alpha:g}"}
            rec.update(prompt_idx=int(r["prompt_idx"]), content=r[col])
            rec["id"] = f"{rec['quadrant']}:{rec['concept']}:{rec['prompt_idx']}:{rec['config']}:{rec['alpha']}"
            out.append(rec)
    return out


def _call(client, medium: str, rec: dict, run: Path) -> dict:
    from google.genai import types

    off = types.AutomaticFunctionCallingConfig(disable=True)
    if medium == "text":
        cfg = types.GenerateContentConfig(response_mime_type="application/json", response_schema=FLUENCY_SCHEMA,
                                          thinking_config=types.ThinkingConfig(thinking_budget=128),
                                          automatic_function_calling=off)
        r = client.models.generate_content(model=MODEL, contents=FLUENCY_PROMPT.format(text=rec["content"]), config=cfg)
        js = json.loads(r.text)
        return {"score": int(js["score"]), "reasoning": js.get("reasoning", "")}
    cfg = types.GenerateContentConfig(response_mime_type="application/json", response_schema=COHERENCE_SCHEMA,
                                      thinking_config=types.ThinkingConfig(thinking_budget=512),
                                      automatic_function_calling=off)
    data = (run / "generations" / rec["content"]).read_bytes()
    r = client.models.generate_content(
        model=MODEL, contents=[types.Part.from_bytes(data=data, mime_type="image/png"), COHERENCE_PROMPT], config=cfg)
    js = json.loads(r.text)
    return {"score": COHERENCE_SCORE[js["verdict"]], "verdict": js["verdict"], "reasoning": js.get("reasoning", "")}


def _run(run, medium: str, name: str, configs, workers: int, limit, log) -> Path:
    from google import genai

    run = Path(run)
    (run / "scores").mkdir(parents=True, exist_ok=True)
    raw = run / "scores" / f"{name}.jsonl"
    done = {json.loads(line)["id"] for line in open(raw)} if raw.exists() else set()
    todo = [r for r in items(run, medium, configs) if r["id"] not in done][:limit]
    log(f"[{name}] {len(todo)} to score ({len(done)} done)")
    client = genai.Client(api_key=os.environ["GEMINI_API_KEY"])
    lock, failed = threading.Lock(), [0]
    with open(raw, "a") as f:
        def one(rec):
            for attempt in range(5):
                try:
                    res = _call(client, medium, rec, run)
                    break
                except Exception as e:                                # rate limits, transient API errors
                    if attempt == 4:
                        log(f"  failed {rec['id']}: {e}")
                        with lock:
                            failed[0] += 1
                        return
                    time.sleep(2 ** attempt)
            out = {k: v for k, v in rec.items() if k != "content"} | res
            with lock:
                f.write(json.dumps(out, ensure_ascii=False) + "\n")
                f.flush()
        with ThreadPoolExecutor(workers) as ex:
            list(ex.map(one, todo))
    path = write_scores(raw)
    if failed[0]:
        raise RuntimeError(f"{failed[0]} outputs could not be scored and are missing from {path}; run again to retry")
    return path


def write_scores(raw: str | Path) -> Path:
    raw = Path(raw)
    out = raw.with_name(raw.stem + "_scores.csv")
    with open(out, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(COLUMNS)
        for r in sorted(map(json.loads, open(raw)), key=lambda r: r["id"]):
            w.writerow([r[c] for c in COLUMNS])
    return out


def fluency(run, workers: int = 32, limit: int | None = None, configs=None, log=print) -> Path:
    """Score every steered text output (of `configs`, default all) and every baseline."""
    return _run(run, "text", "fluency", configs, workers, limit, log)


def coherence(run, workers: int = 16, limit: int | None = None, configs=("mid",), log=print) -> Path:
    """Score steered images of `configs` (the paper scores the middle layer range) and every baseline."""
    return _run(run, "image", "coherence", configs, workers, limit, log)
